"""
Builds the extraction and product-review reports from the generated manifest.

Usage: python scripts/build_reports.py   (run after scripts/extract_catalog.py)
"""
import json
import os
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
products = json.load(open(os.path.join(ROOT, "src", "data", "products.json"), encoding="utf-8"))
stats = json.load(open(os.path.join(ROOT, "reports", "extraction-stats.json"), encoding="utf-8"))

DIV = {"police": "EVERBRIGHT POLICE STORE", "uniform": "EVERBRIGHT UNIFORMS", "bags": "EVERBRIGHT FIRE AND SAFETY"}
LABELS = {
    "security-shirts": "Security Shirts", "security-uniform-sets": "Security Uniform Sets",
    "ladies-guard-uniforms": "Ladies Guard Uniforms", "ladies-guard-uniforms-waistcoat": "Ladies Guard Uniforms with Waistcoat",
    "caps-berets": "Caps & Berets", "shoulder-flaps": "Shoulder Flaps", "shoulder-pads": "Shoulder Pads",
    "chef-coat-sets": "Chef Coat Sets", "kitchen-aprons": "Kitchen Aprons", "multi-purpose-aprons": "Multi-Purpose Aprons",
    "waterproof-aprons": "Waterproof Aprons", "cafe-aprons": "Cafe Aprons", "housekeeping-shirts": "Housekeeping Shirts",
    "regular-shirts": "Regular Shirts", "safari-suits": "Safari Suits", "waistcoats": "Waistcoats",
}

by_pdf = defaultdict(list)
for p in products:
    by_pdf[p["sourcePdf"]].append(p)
div_count = Counter(p["division"] for p in products)
cat_count = Counter((p["division"], p["category"]) for p in products)
review = [p for p in products if p["reviewRequired"]]
renamed = [p for p in products if p["nameSource"] == "catalogue-label" and p["name"].lower() not in p["sourceLabel"].lower()]
views = Counter(i["view"] for p in products for i in p["images"])

L = []
L.append("# PDF Extraction Report — Everbright Uniforms\n")
L.append("Generated by `scripts/extract_catalog.py` + `scripts/build_reports.py`. The original PDFs in "
         "`reference pdfs/` were only read, never modified.\n")
L.append("## Summary\n")
L.append(f"- PDFs inspected: **{len(stats)}** (all PDFs found in the project)")
L.append(f"- Pages inspected: **{sum(s['pages'] for s in stats)}**")
L.append(f"- Products identified: **{len(products)}** (one product per catalogue page)")
L.append(f"- Images written: **{sum(s['images'] for s in stats)}** WebP files in `public/catalog/`")
L.append(f"- {DIV['police']}: **{div_count['police']}** products")
L.append(f"- {DIV['uniform']}: **{div_count['uniform']}** products")
L.append(f"- {DIV['bags']}: **{div_count.get('bags', 0)}** products — no bag catalogue was supplied")
L.append(f"- Products flagged for manual review: **{len(review)}**")
L.append("- Images excluded because a person is visible: **0** — every page was inspected visually; all photographs are "
         "isolated products, flat-lays or ghost-mannequin shots with no faces, bodies or mannequin heads.")
L.append("- Missing product photographs: **0** for supplied products (every product has at least one real photograph).\n")

L.append("## Method\n")
L.append("1. Every PDF was opened with PyMuPDF. None contain a text layer (all text is printed inside the images), and each "
         "page holds exactly one embedded JPEG — the product plate. That original JPEG was extracted at full resolution "
         "(no page re-rendering).")
L.append("2. Product names, numbers and colourways were transcribed from the labels printed on each plate (verified from "
         "enlarged label crops).")
L.append("3. Printed banners, name tags and 'FRONT VIEW / BACK VIEW' captions were removed by cropping. Where a plate shows a "
         "front and a back view, the split point is found automatically (the emptiest column between the two garments) "
         "and each view is trimmed to its content. Images were never retouched, recoloured or generated.")
L.append("4. Each product folder holds: `-01` front (or main) view, `-02` back view, `-03` front-and-back view and, for "
         "multi-purpose aprons, `-04` detail callouts printed in the catalogue.")
L.append("5. Contact sheets of every output image are in `reports/contact-sheets/` for quick review.\n")
L.append(f"Image views written: " + ", ".join(f"{k}: {v}" for k, v in sorted(views.items())) + "\n")

L.append("## Per-PDF results\n")
L.append("| PDF | Pages | Products | Images | Division | Categories |")
L.append("|---|---:|---:|---:|---|---|")
for s in stats:
    ps = by_pdf[s["pdf"]]
    cats = sorted({LABELS[p["category"]] for p in ps})
    L.append(f"| {s['pdf']} | {s['pages']} | {s['products']} | {s['images']} | {DIV[s['division']]} | {', '.join(cats)} |")
L.append("")

L.append("## Classification\n")
L.append("Rule applied per product, using the printed headings and branding on each plate:\n")
L.append("- Pages titled or branded **Police Store / Security** → EVERBRIGHT UNIFORM POLICE.")
L.append("- All other professional clothing → EVERBRIGHT UNIFORM.")
L.append("- Leather protective document bags → EVERBRIGHT PROTECTIVE BAGS (none supplied).\n")
L.append("| Division | Category | Products |")
L.append("|---|---|---:|")
for (d, c), n in sorted(cat_count.items(), key=lambda x: (x[0][0] != "police", x[0][1])):
    L.append(f"| {DIV[d]} | {LABELS[c]} | {n} |")
L.append("")
L.append("Categories requested in the brief but with **no supplied products**: Police (non-security) uniforms, Military "
         "uniforms, Doctor uniforms, Medical uniforms, Hospital uniforms, and all Protective Bags. These categories are not "
         "shown on the site until products exist.\n")

L.append("## Ambiguous classification\n")
L.append("- **E P S House Keeping Shirt's.pdf (17 products)** — the filename abbreviation 'E P S' may mean Everbright Police "
         "Store, but the pages show unbranded housekeeping shirts with no police or security reference. They are shown under "
         "EVERBRIGHT UNIFORM → Housekeeping Shirts (as 'EPS Series A / B') and flagged `reviewRequired`. Set "
         "`brand.showReviewRequiredProducts = false` in `src/config/brand.ts` to hide all flagged products, or move them by "
         "changing their `division` in the extraction script.\n")

L.append("## Items requiring manual review\n")
L.append("| Product id | Name | Source | Reason |")
L.append("|---|---|---|---|")
for p in review:
    L.append(f"| `{p['id']}` | {p['name']} | {p['sourcePdf']} p.{p['sourcePage'][0]} | {' '.join(p['reviewNotes'])} |")
L.append("")

L.append("## Name normalisation\n")
L.append("Display names use standard spelling; the exact printed label is preserved in `sourceLabel` for every product. "
         "Corrections applied: 'Coffe' → 'Coffee', 'Appolo' → 'Apollo', 'Wase Coat' → 'Waistcoat', 'Strips' → 'Stripes'. "
         "Fabric names such as 'Shemray' and 'Fila-Fil' are kept exactly as printed.\n")

L.append("## Source quality notes\n")
L.append("- EPS Series A pages (1–10) are low resolution (768 px wide plates); the resulting images are small.")
L.append("- Many plates carry Everbright watermarks across the background; these are part of the original photographs and "
         "were kept.")
L.append("- No product descriptions, sizes or available-colour lists are printed in the PDFs, so those fields are empty. "
         "Only printed facts are shown (e.g. 'Water proof material', multi-purpose apron detail callouts, "
         "'Reversible — same design on both sides', 'Previous design').")
open(os.path.join(ROOT, "reports", "pdf-extraction-report.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")

R = ["# Product Review Report — Everbright Uniforms\n",
     f"All {len(products)} products with their source and classification. Products marked **Review** need the owner's "
     "confirmation before launch.\n",
     "| # | Product id | Display name | Printed label | Division | Category | Source | Images | Status |",
     "|---:|---|---|---|---|---|---|---:|---|"]
for i, p in enumerate(products, 1):
    status = "Review" if p["reviewRequired"] else "OK"
    R.append(f"| {i} | `{p['id']}` | {p['name']} | {p['sourceLabel']} | {DIV[p['division']]} | {LABELS[p['category']]} | "
             f"{p['sourcePdf']} p.{p['sourcePage'][0]} | {len(p['images'])} | {status} |")
open(os.path.join(ROOT, "reports", "product-review-report.md"), "w", encoding="utf-8").write("\n".join(R) + "\n")
print("reports written:", len(products), "products,", len(review), "flagged")
